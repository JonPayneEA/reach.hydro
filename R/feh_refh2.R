#' Summarise a ReFH2 simulation result
#'
#' @param result  `data.table` returned by [refh2_run()].
#' @param area_km2 Catchment area \[km²\] for conversion to m³/s. If `NULL`,
#'                 outputs remain in mm/timestep.
#' @param dt_hr   Timestep \[hours\]. If `NULL`, inferred from `result`.
#'
#' @return A named list: `peak_mm`, `peak_m3s`, `volume_mm`, `volume_Mm3`,
#'   `time_to_peak_hr`.
#' @export
refh2_summary <- function(result, area_km2 = NULL, dt_hr = NULL) {
  if (is.null(dt_hr))
    dt_hr <- diff(result$time_min[1:2]) / 60

  peak_mm <- attr(result, "peak_flow_mm")
  vol_mm  <- attr(result, "flood_volume_mm")  # mm·hr
  ttp_hr  <- result$time_hr[which.max(result$Q_mm)]

  out <- list(
    peak_mm       = peak_mm,
    volume_mm_hr  = vol_mm,
    time_to_peak_hr = ttp_hr
  )

  if (!is.null(area_km2)) {
    # mm/ts * km2 -> m3/s: (mm/1000) * (km2 * 1e6) / (dt_hr * 3600)
    out$peak_m3s  <- mm_to_m3s(peak_mm, area_km2, dt_hr)
    out$volume_Mm3 <- vol_mm * area_km2 * 1e6 / (1000 * 1e6)  # million m3
  }

  out
}
