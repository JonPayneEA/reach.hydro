#' Run the ReFH2 rainfall-runoff model
#'
#' Given a design storm hyetograph and ReFH2 parameters, simulates the direct
#' runoff hydrograph, baseflow, and total flow. The loss model uses a simple
#' probability-distributed soil moisture accounting, and the routing uses
#' two linear reservoirs in series with a time-to-peak unit hydrograph.
#'
#' @param storm    A `data.table` from [feh_design_storm()] with columns
#'                 `time_min` and `rainfall_mm`. Or any `data.table` with
#'                 those columns and a consistent timestep.
#' @param params   A `ReFH2Params` object from [refh2_params()], or a named
#'                 list with the same fields.
#' @param baseflow_0 Initial baseflow \[m³/s\] (scaled by area). Default 0.
#'
#' @return A `data.table` with columns:
#'   \describe{
#'     \item{time_min, time_hr}{Time axes.}
#'     \item{rainfall_mm}{Input rainfall (per timestep).}
#'     \item{loss_mm}{Infiltration loss (per timestep).}
#'     \item{net_rain_mm}{Net (effective) rainfall = rainfall - loss.}
#'     \item{C}{Soil moisture state \[mm\].}
#'     \item{Qd_mm}{Direct runoff depth per timestep \[mm\].}
#'     \item{Qb_mm}{Baseflow depth per timestep \[mm\].}
#'     \item{Q_mm}{Total flow depth per timestep \[mm\].}
#'   }
#'   Attributes: `params`, `peak_flow_mm`, `flood_volume_mm`.
#'
#' @seealso [refh2_params()], [feh_design_storm()]
#' @export
refh2_run <- function(storm, params, baseflow_0 = 0) {

  if (!inherits(params, "ReFH2Params"))
    params <- structure(params, class = "ReFH2Params")

  if (!data.table::is.data.table(storm))
    storm <- data.table::as.data.table(storm)

  req <- c("time_min", "rainfall_mm")
  missing_cols <- setdiff(req, names(storm))
  if (length(missing_cols) > 0)
    stop(sprintf("refh2_run: storm missing columns: %s",
                 paste(missing_cols, collapse = ", ")), call. = FALSE)

  n   <- nrow(storm)
  dt_hr <- diff(storm$time_min[1:2]) / 60  # timestep in hours

  # ---- Pre-allocate output --------------------------------------------------
  out <- data.table::copy(storm)
  out[, c("loss_mm", "net_rain_mm", "C",
          "Qd_mm", "Qb_mm", "Q_mm") := NA_real_]
  out[, time_hr := time_min / 60]

  # ---- Routing kernel: triangular UH → two cascaded linear reservoirs ------
  # Tp in timesteps
  Tp_steps <- max(1L, round(params$Tp / dt_hr))
  uh       <- .refh2_uh(Tp_steps, n)

  # ---- Loss model state -----------------------------------------------------
  C    <- params$Cini  # current soil moisture [mm]
  Cmax <- params$Cmax

  net_rain <- numeric(n)

  for (t in seq_len(n)) {
    P <- max(0, storm$rainfall_mm[t])

    # Simple proportional loss: infiltration = P * (1 - C/Cmax)
    if (Cmax > 0) {
      f_sat   <- C / Cmax
      net_t   <- P * f_sat
      loss_t  <- P - net_t
      C       <- min(C + loss_t, Cmax)
    } else {
      net_t   <- P
      loss_t  <- 0
    }

    out[t, loss_mm    := loss_t]
    out[t, net_rain_mm := net_t]
    out[t, C          := C]
    net_rain[t] <- net_t
  }

  # ---- Route net rain through UH (convolution) ------------------------------
  Qd <- stats::filter(net_rain, uh, sides = 1)
  Qd[is.na(Qd)] <- 0

  # ---- Baseflow: linear recession with recharge from net rain ---------------
  Qb    <- numeric(n)
  Kb    <- params$Kb
  BR    <- params$BR
  bl_steps <- max(1L, round(params$BL / dt_hr))

  Qb_cur <- baseflow_0
  for (t in seq_len(n)) {
    # Lagged recharge
    t_lag   <- max(1L, t - bl_steps)
    recharge <- BR * net_rain[t_lag] * dt_hr
    Qb_cur  <- Qb_cur * Kb + recharge
    Qb[t]   <- Qb_cur
  }

  # ---- Combine --------------------------------------------------------------
  out[, Qd_mm := pmax(0, Qd)]
  out[, Qb_mm := pmax(0, Qb)]
  out[, Q_mm  := Qd_mm + Qb_mm]

  attr(out, "params")          <- params
  attr(out, "peak_flow_mm")    <- max(out$Q_mm)
  attr(out, "flood_volume_mm") <- sum(out$Q_mm) * dt_hr  # mm·hr (depth × time)

  out
}

# Internal: triangular unit hydrograph kernel normalised to unit volume
# Tp_steps: time-to-peak in timesteps; n: total length
.refh2_uh <- function(Tp_steps, n) {
  t_seq <- seq_len(n)
  uh    <- ifelse(t_seq <= Tp_steps,
                  t_seq / Tp_steps^2,
                  pmax(0, 2 / Tp_steps - t_seq / Tp_steps^2))
  uh / sum(uh)
}

