#' Estimate ReFH2 parameters from FEH catchment descriptors
#'
#' Applies regression equations to derive ReFH2 model parameters from standard
#' FEH catchment descriptors.
#'
#' @section WARNING — unverified coefficients:
#' The regression coefficients in this function were generated by an AI model
#' and have **not** been verified against the authoritative source documents.
#' The full ReFH2 parameter equations are proprietary (Wallingford
#' HydroSolutions 2016) and may require a licence. **Do not use this function
#' for real flood estimation** until the coefficients have been checked and
#' replaced with verified values. See the file header in `feh_refh2.R` for
#' the full action list.
#'
#' @param area      Catchment area \[km²\]. (AREA)
#' @param bfihost   Baseflow index from HOST soils \[0-1\]. (BFIHOST)
#' @param saar      Standard average annual rainfall \[mm\]. (SAAR)
#' @param farl      Index of flood attenuation by reservoirs and lakes \[0-1\].
#'                  (FARL; default 1.0 = no attenuation)
#' @param urbext    Fraction of catchment urbanised (FEH URBEXT2000).
#'                  Default 0.0 = rural.
#' @param season    `"summer"` (default) or `"winter"`. Affects Cini.
#'
#' @return A list of class `"ReFH2Params"` containing:
#'   \describe{
#'     \item{Cmax}{Maximum soil moisture capacity \[mm\].}
#'     \item{Cini}{Initial soil moisture content \[mm\] (seasonal).}
#'     \item{alpha}{BRC — proportion of runoff going to fast store.}
#'     \item{Tp}{Time-to-peak of unit hydrograph \[hours\].}
#'     \item{BL}{Baseflow lag \[hours\].}
#'     \item{BR}{Baseflow recharge parameter \[—\].}
#'     \item{Kb}{Baseflow recession constant \[—\].}
#'   }
#'
#' @examples
#' p <- refh2_params(area = 250, bfihost = 0.45, saar = 850, farl = 0.98)
#' p
#'
#' @seealso [refh2_run()]
#' @export
refh2_params <- function(area,
                         bfihost,
                         saar,
                         farl   = 1.0,
                         urbext = 0.0,
                         season = "summer") {

  checkmate::assert_number(area,    lower = 0)
  checkmate::assert_number(bfihost, lower = 0, upper = 1)
  checkmate::assert_number(saar,    lower = 0)
  checkmate::assert_number(farl,    lower = 0, upper = 1)
  checkmate::assert_number(urbext,  lower = 0, upper = 1)
  season <- match.arg(season, c("summer", "winter"))

  warning(
    "refh2_params(): regression coefficients are UNVERIFIED and may be ",
    "incorrect or proprietary. Do not use for real flood estimation. ",
    "See ?refh2_params and the feh_refh2.R file header for details.",
    call. = FALSE
  )

  # !! UNVERIFIED — check all coefficients below against Kjeldsen (2007)
  # !! and Wallingford HydroSolutions (2016) before operational use.
  # Urbanisation adjustment to BFIHOST (Kjeldsen 2007, eq 15)
  bfi_adj <- bfihost * (1 - 0.496 * urbext^0.376)

  # Cmax: maximum soil moisture capacity [mm] (Kjeldsen 2007, Table 5)
  Cmax <- exp(3.2397 + 0.6099 * log(1 + saar) -
              0.9926 * log(1 + bfi_adj))

  # Cini: initial condition (fraction of Cmax) — seasonal (Table 5)
  frac_ini <- if (season == "summer") {
    exp(-0.0050 * saar) * (1 - bfi_adj)^0.4
  } else {
    0.5 * exp(-0.0050 * saar) * (1 - bfi_adj)^0.4
  }
  Cini <- Cmax * pmin(frac_ini, 0.99)

  # Tp: time-to-peak [hours] (Kjeldsen 2007, Table 6)
  Tp <- exp(-1.6090 + 0.8294 * log(area) -
            0.4271 * log(1 + saar) + 0.3015 * log(1 + bfi_adj) +
            0.0709 * log(farl))

  # alpha: baseflow recharge coefficient (BRC) (Table 6)
  alpha <- pmin(pmax(
    0.9 * bfi_adj^1.3,
    0), 0.99)

  # BL: baseflow lag [hours] (Table 7)
  BL <- exp(0.4598 + 0.7533 * log(area) -
            0.3004 * log(1 + saar))

  # BR: baseflow recharge (Table 7)
  BR <- exp(-1.6935 + 0.4999 * log(area) + 0.2745 * log(1 + saar))

  # Kb: baseflow recession (Table 7) — empirical
  Kb <- 0.5 * (1 + bfi_adj)

  structure(
    list(Cmax = Cmax, Cini = Cini, alpha = alpha,
         Tp = Tp, BL = BL, BR = BR, Kb = Kb,
         area = area, bfihost = bfihost, saar = saar,
         farl = farl, urbext = urbext, season = season),
    class = "ReFH2Params"
  )
}

#' @export
print.ReFH2Params <- function(x, ...) {
  cat(sprintf("<ReFH2Params> area=%.1f km\u00b2 | BFIHOST=%.3f | SAAR=%d mm | %s\n",
              x$area, x$bfihost, round(x$saar), x$season))
  cat(sprintf("  Cmax=%.1f mm | Cini=%.1f mm | alpha=%.3f\n",
              x$Cmax, x$Cini, x$alpha))
  cat(sprintf("  Tp=%.2f hr | BL=%.2f hr | BR=%.3f | Kb=%.3f\n",
              x$Tp, x$BL, x$BR, x$Kb))
  invisible(x)
}

